#!/usr/bin/env python3
"""
generate_sprites.py — Create pixel-art sprite PNGs for gameboy-v2

Run this to regenerate the source PNGs. Edit this file to change sprite art.
Then run convert_tiles.py to produce the binary assets.
"""
from PIL import Image

MAGENTA = (255, 0, 255, 0)  # transparent

def save(name, w, h, put_fn):
    img = Image.new('RGBA', (w, h), MAGENTA)
    put_fn(img)
    img.save(f"{name}.png")

# --- Player (16x20): dino character ---
def make_player(img):
    Y = (255, 220, 0, 255)
    D = (200, 170, 0, 255)
    B = (0, 0, 0, 255)
    W = (255, 255, 255, 255)
    # Head
    for y in range(0, 7):
        for x in range(4, 14):
            img.putpixel((x, y), Y)
    img.putpixel((10, 2), W); img.putpixel((11, 2), W)
    img.putpixel((11, 3), B)
    img.putpixel((13, 5), B); img.putpixel((14, 5), B)
    # Body
    for y in range(7, 15):
        for x in range(2, 12):
            img.putpixel((x, y), Y)
    # Arm
    for y in range(8, 12):
        img.putpixel((12, y), D); img.putpixel((13, y), D)
    # Tail
    for y in range(10, 15):
        img.putpixel((0, y), D); img.putpixel((1, y), D)
    # Legs
    for y in range(15, 20):
        img.putpixel((3, y), D); img.putpixel((4, y), D)
        img.putpixel((8, y), D); img.putpixel((9, y), D)

save("player", 16, 20, make_player)

# --- Obstacles: cacti ---
def make_cactus(img):
    G = (50, 140, 50, 255)
    D = (30, 100, 30, 255)
    w, h = img.size
    # Trunk
    for y in range(h):
        for x in range(4, 8):
            img.putpixel((x, y), G)
        img.putpixel((4, y), D)
    # Left arm
    if h > 15:
        for y in range(h//3, h//3 + 8):
            for x in range(1, 4):
                img.putpixel((x, y), G)
        for y in range(h//3, h//3 + 4):
            img.putpixel((1, y), D)
    # Right arm
    if h > 12:
        for y in range(h//2, h//2 + 6):
            for x in range(8, 11):
                img.putpixel((x, y), G)

save("obs_0", 12, 20, make_cactus)
save("obs_1", 12, 25, make_cactus)
save("obs_2", 12, 30, make_cactus)

# --- Ground (320x4) ---
def make_ground(img):
    w, h = img.size
    G = (50, 140, 50, 255)
    D = (30, 100, 30, 255)
    B = (139, 90, 43, 255)
    w, h = img.size
    for y in range(h):
        for x in range(w):
            if y == 0:
                img.putpixel((x, y), D)
            elif (x + y) % 7 == 0:
                img.putpixel((x, y), B)
            else:
                img.putpixel((x, y), G)

save("ground", 16, 4, make_ground)

# --- Digits (8x10 each) ---
DIGIT_PATTERNS = [
    [0x3C,0x66,0x6E,0x76,0x66,0x66,0x66,0x66,0x66,0x3C],
    [0x18,0x38,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x7E],
    [0x3C,0x66,0x06,0x06,0x0C,0x18,0x30,0x60,0x66,0x7E],
    [0x3C,0x66,0x06,0x06,0x1C,0x06,0x06,0x06,0x66,0x3C],
    [0x0C,0x1C,0x2C,0x4C,0x4C,0x7E,0x0C,0x0C,0x0C,0x0C],
    [0x7E,0x60,0x60,0x7C,0x06,0x06,0x06,0x06,0x66,0x3C],
    [0x3C,0x66,0x60,0x60,0x7C,0x66,0x66,0x66,0x66,0x3C],
    [0x7E,0x66,0x06,0x0C,0x0C,0x18,0x18,0x18,0x18,0x18],
    [0x3C,0x66,0x66,0x66,0x3C,0x66,0x66,0x66,0x66,0x3C],
    [0x3C,0x66,0x66,0x66,0x3E,0x06,0x06,0x06,0x66,0x3C],
]

W = (255, 255, 255, 255)
for d in range(10):
    def make_digit(img, pat=DIGIT_PATTERNS[d]):
        for row in range(10):
            for col in range(8):
                if pat[row] & (0x80 >> col):
                    img.putpixel((col, row), W)
    save(f"digit_{d}", 8, 10, make_digit)

# --- Text sprites ---
LETTER_PATTERNS = {
    'A': [0x1C,0x36,0x63,0x63,0x63,0x7F,0x63,0x63,0x63,0x63,0x00,0x00,0x00,0x00],
    'D': [0x7C,0x66,0x63,0x63,0x63,0x63,0x63,0x63,0x66,0x7C,0x00,0x00,0x00,0x00],
    'E': [0x7F,0x60,0x60,0x60,0x7E,0x60,0x60,0x60,0x60,0x7F,0x00,0x00,0x00,0x00],
    'G': [0x3E,0x63,0x60,0x60,0x60,0x6F,0x63,0x63,0x63,0x3E,0x00,0x00,0x00,0x00],
    'I': [0x7E,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x7E,0x00,0x00,0x00,0x00],
    'M': [0x63,0x77,0x7F,0x6B,0x63,0x63,0x63,0x63,0x63,0x63,0x00,0x00,0x00,0x00],
    'N': [0x63,0x73,0x7B,0x7F,0x6F,0x67,0x63,0x63,0x63,0x63,0x00,0x00,0x00,0x00],
    'O': [0x3E,0x63,0x63,0x63,0x63,0x63,0x63,0x63,0x63,0x3E,0x00,0x00,0x00,0x00],
    'R': [0x7E,0x63,0x63,0x63,0x7E,0x6C,0x66,0x63,0x63,0x63,0x00,0x00,0x00,0x00],
    'U': [0x63,0x63,0x63,0x63,0x63,0x63,0x63,0x63,0x63,0x3E,0x00,0x00,0x00,0x00],
    'V': [0x63,0x63,0x63,0x63,0x63,0x63,0x36,0x36,0x1C,0x1C,0x00,0x00,0x00,0x00],
    ' ': [0x00]*14,
}

def make_text(text, color, name):
    char_w, char_h = 8, 14
    w = len(text) * char_w
    def draw(img):
        for ci, ch in enumerate(text):
            pat = LETTER_PATTERNS.get(ch, LETTER_PATTERNS[' '])
            for row in range(min(len(pat), char_h)):
                for col in range(char_w):
                    if pat[row] & (0x80 >> col):
                        img.putpixel((ci * char_w + col, row), color)
    save(name, w, char_h, draw)

make_text("DINO RUN", (255, 220, 0, 255), "title")
make_text("GAME OVER", (255, 255, 255, 255), "gameover")

print("Generated sprite PNGs")
