#!/usr/bin/env python3
"""gen-predef.py GNU-PREFIX > predef.h — the predefined macros of the GCC we replace, for our cpp.

GCC predefines ~430 macros for the target (arm-linux-gnueabihf, cortex-a7, neon-vfpv4, hard float, ARM state) that
headers branch on: musl's setjmp saves d8-d15 only under __VFP_FP__, its atomics pick ldrex/strex by __ARM_ARCH_7A__,
features.h picks `inline` by __STDC_VERSION__. The BASE is `gcc -nostdinc -dM -E` (gnu17, -O0, hosted, no PIC;
-nostdinc: without the stdc-predef.h GCC includes implicitly). Each option that changes the set gets a DELTA against
the base, from running GCC with that option alone; cpp composes one delta per option group (see cpp.c: predefines()).
The table is generated, never hand-edited: regenerate with the reference GCC to follow it."""
import subprocess, sys

gnu = sys.argv[1]
def dump(opts):
    out = subprocess.run([gnu + "gcc", "-nostdinc"] + opts + ["-dM", "-E", "-x", "c", "/dev/null"] if "-x" not in opts else
                         [gnu + "gcc", "-nostdinc"] + opts + ["-dM", "-E", "/dev/null"], capture_output=True, text=True, check=True).stdout
    m = {}
    for line in out.splitlines():
        assert line.startswith("#define "), line
        rest = line[8:]
        name, _, val = rest.partition(" ")        # a function-like one's name carries its parameters: __INT64_C(c)
        m[name] = val
    return m

def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

# each option group's non-default members (the default is the base); cpp.c maps its option state onto these keys
DELTAS = ["-O1", "-O2", "-O3", "-Os", "-Oz", "-Og", "-ffast-math",
          "-fpic", "-fPIC", "-fpie", "-fPIE", "-ffreestanding", "-pthread", "-mfloat-abi=soft", "-mfloat-abi=softfp",
          "-std=c89", "-std=gnu89", "-std=iso9899:199409", "-std=c99", "-std=gnu99", "-std=c11", "-std=gnu11",
          "-std=c17", "-std=c2x", "-std=gnu2x", "-x assembler-with-cpp", "-fsigned-char",
          "-fshort-wchar", "-march=armv7-a", "-mfpu=vfp", "-mno-unaligned-access", "-mthumb",
          "-fstack-protector", "-fstack-protector-strong", "-fstack-protector-all", "-fstack-protector-explicit"]
base = dump([])
version = subprocess.run([gnu + "gcc", "-dumpfullversion"], capture_output=True, text=True).stdout.strip()
target = subprocess.run([gnu + "gcc", "-dumpmachine"], capture_output=True, text=True).stdout.strip()
print("/* predef.h — GENERATED by gen-predef.py from GCC %s (%s): do not edit, regenerate. */" % (version, target))
print("static const char *const predef_base[][2] = {")
for k in sorted(base):
    print("\t{ %s, %s }," % (cstr(k), cstr(base[k])))
print("};")
print("/* option -> the macros it defines, changes (val) or removes (val NULL), relative to the base */")
print("static const struct { const char *opt, *name, *val; } predef_delta[] = {")
for o in DELTAS:
    d = dump(o.split())
    for k in sorted(set(base) | set(d)):
        if k not in d: print("\t{ %s, %s, NULL }," % (cstr(o), cstr(k)))
        elif base.get(k) != d[k]: print("\t{ %s, %s, %s }," % (cstr(o), cstr(k), cstr(d[k])))
print("};")
